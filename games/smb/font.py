_WIDE = {"(c)": "0000011 0001111 0011110 0111100 0111000 1010000 1000000"}   # slot $CF: a leaf (no copyright sign)
THIN = set("ABCDEFGHIJKLMNOPQRSTUVWXYZ")   # letters: stems doubled, bars stay 1 px (our look); digits fully bold


def glyph(ch, bold=True) -> np.ndarray:
    """-> 8x8 of 0/1"""
    out = np.zeros((8, 8), np.uint8)
    if ch in _WIDE:
        for y, r in enumerate(_WIDE[ch].split()):
            out[y, :7] = [int(c) for c in r]
        return out
    for y, r in enumerate(_F[ch].split()):
        out[y, :5] = [int(c) for c in r]
    if bold:
        b = out.copy()
        b[:, 1:] |= out[:, :-1]
        if ch in THIN:                     # embolden only pixels that belong to vertical runs
            v = np.zeros_like(out)
            v[1:] |= out[1:] & out[:-1]
            v[:-1] |= out[:-1] & out[1:]
            b = out.copy()
            b[:, 1:] |= v[:, :-1]
        out = b
    return out
